"""MM-Food-100K, streamed from the Hugging Face Hub (labels) and the Codatta CDN (photos).

Source: https://huggingface.co/datasets/Codatta/MM-Food-100K
The Hub repository only holds one CSV (28 MB) with labels and an ``image_url``
per row; it is downloaded once and cached, the photos are fetched on the fly.
The nutrition labels were generated by language models: weak labels, for
pre-training only.
"""

from __future__ import annotations

import csv
import io
import json
import math
import re

from ._streaming import CACHE_DIR, StreamingFoodDataset, cached, fetch, hash_split, to_float

CSV_URL = "https://huggingface.co/datasets/Codatta/MM-Food-100K/resolve/main/MM-Food-100K.csv"
_GRAMS = re.compile(r"(\d+(?:\.\d+)?)\s*g\b", re.IGNORECASE)


def _json(text: str, default):
    try:
        return json.loads(text)
    except (TypeError, ValueError):
        return default


def _portion_grams(portions: list) -> float:
    """Sum of the gram amounts in e.g. ``["noodles:200g", "beef:100g"]`` (nan if none)."""
    grams = [float(m.group(1)) for p in portions if (m := _GRAMS.search(str(p)))]
    return sum(grams) if grams else math.nan


class MMFood100K(StreamingFoodDataset):
    """100,000 user photos with model-generated dish, ingredient and nutrition labels.

    Args:
        split: ``train`` / ``val`` / ``all``. There is no official split; ``val``
            is a hash-based hold-out (one photo = one dish).
        val_fraction: share of the photos used for ``val``.
        min_food_prob: drop rows whose ``food_prob`` is below this value.
        **kwargs: see ``StreamingFoodDataset``. Photos are ~1 MB each, a full
            epoch transfers on the order of 100 GB; dead links are skipped.

    Extra sample keys: ``dish_name``, ``food_type``, ``cooking_method``,
    ``ingredients``, ``portions`` (raw strings), ``food_prob``.
    ``mass_g`` is the sum of the gram amounts in ``portions``.
    """

    name = "mm_food_100k"

    def __init__(self, split: str = "train", val_fraction: float = 0.02, min_food_prob: float = 0.0, **kwargs):
        super().__init__(**kwargs)
        if split not in ("train", "val", "all"):
            raise ValueError(f"unknown split {split!r}")
        self.split = split

        text = cached(CACHE_DIR / self.name / "MM-Food-100K.csv", lambda: fetch(CSV_URL, timeout=300)).decode("utf-8-sig")
        for row in csv.DictReader(io.StringIO(text)):
            url = row["image_url"]
            if not url or to_float(row["food_prob"]) < min_food_prob:
                continue
            image_id = url.rsplit("/", 1)[-1]
            part = ("train", "val")[hash_split(image_id, (1 - val_fraction, val_fraction))]
            if split not in ("all", part):
                continue
            nutrition = _json(row["nutritional_profile"], {})
            portions = _json(row["portion_size"], [])
            self.records.append({
                "dish_id": image_id,
                "image_id": image_id,
                "mass_g": _portion_grams(portions),
                "kcal": to_float(nutrition.get("calories_kcal")),
                "fat_g": to_float(nutrition.get("fat_g")),
                "carb_g": to_float(nutrition.get("carbohydrate_g")),
                "protein_g": to_float(nutrition.get("protein_g")),
                "dish_name": row["dish_name"],
                "food_type": row["food_type"],
                "cooking_method": row["cooking_method"],
                "ingredients": _json(row["ingredients"], []),
                "portions": portions,
                "food_prob": to_float(row["food_prob"]),
                "_url": url,
            })

    def _load(self, rec: dict) -> dict:
        return self._sample(rec, self._image(rec["image_id"], lambda: fetch(rec["_url"])))
